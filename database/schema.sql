-- ============================================================
-- PORTAL SAÚDE RH
-- Banco de dados: PostgreSQL
-- Script de criação da estrutura do banco de dados
-- ============================================================

-- ============================================================
-- Tabela: usuario
-- ============================================================

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    matricula VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tentativas_login INTEGER NOT NULL DEFAULT 0,
    bloqueado_ate TIMESTAMP
);

-- ============================================================
-- Tabela: categoria
-- ============================================================

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    descricao VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

-- ============================================================
-- Tabela: solicitacao
-- ============================================================

CREATE TABLE solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(255) NOT NULL UNIQUE,
    usuario_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    descricao TEXT NOT NULL,
    status VARCHAR(255) NOT NULL,
    data_abertura TIMESTAMP NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_solicitacao_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario(id),

    CONSTRAINT fk_solicitacao_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria(id)
);

-- ============================================================
-- Tabela: historico_solicitacao
-- ============================================================

CREATE TABLE historico_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    usuario_id BIGINT,
    data_hora TIMESTAMP NOT NULL,
    acao VARCHAR(255) NOT NULL,
    status_anterior VARCHAR(255),
    novo_status VARCHAR(255),
    observacao TEXT,

    CONSTRAINT fk_historico_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id),

    CONSTRAINT fk_historico_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

-- ============================================================
-- Tabela: resposta_solicitacao
-- ============================================================

CREATE TABLE resposta_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    usuario_resposta_id BIGINT NOT NULL,
    comentario TEXT NOT NULL,
    data_resposta TIMESTAMP NOT NULL,
    nome_original_arquivo VARCHAR(255),
    nome_armazenado_arquivo VARCHAR(255),
    tipo_arquivo VARCHAR(150),
    tamanho_arquivo BIGINT,

    CONSTRAINT fk_resposta_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id),

    CONSTRAINT fk_resposta_usuario
        FOREIGN KEY (usuario_resposta_id) REFERENCES usuario(id)
);

-- ============================================================
-- Tabela: anexo_solicitacao
-- ============================================================

CREATE TABLE anexo_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    nome_original VARCHAR(255) NOT NULL,
    nome_armazenado VARCHAR(255) NOT NULL UNIQUE,
    tipo_conteudo VARCHAR(150) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    data_upload TIMESTAMP NOT NULL,

    CONSTRAINT fk_anexo_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id)
);

-- ============================================================
-- Tabela: anexo_resposta
-- ============================================================

CREATE TABLE anexo_resposta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resposta_id BIGINT NOT NULL,
    nome_original VARCHAR(255) NOT NULL,
    nome_armazenado VARCHAR(255) NOT NULL UNIQUE,
    tipo_conteudo VARCHAR(150) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    data_upload TIMESTAMP NOT NULL,

    CONSTRAINT fk_anexo_resposta
        FOREIGN KEY (resposta_id) REFERENCES resposta_solicitacao(id)
);

-- ============================================================
-- Índices para otimização das consultas
-- ============================================================

CREATE INDEX idx_solicitacao_usuario
    ON solicitacao(usuario_id);

CREATE INDEX idx_solicitacao_categoria
    ON solicitacao(categoria_id);

CREATE INDEX idx_historico_solicitacao
    ON historico_solicitacao(solicitacao_id);

CREATE INDEX idx_historico_usuario
    ON historico_solicitacao(usuario_id);

CREATE INDEX idx_resposta_solicitacao
    ON resposta_solicitacao(solicitacao_id);

CREATE INDEX idx_resposta_usuario
    ON resposta_solicitacao(usuario_resposta_id);

CREATE INDEX idx_anexo_solicitacao
    ON anexo_solicitacao(solicitacao_id);

CREATE INDEX idx_anexo_resposta
    ON anexo_resposta(resposta_id);
